#!/usr/bin/env node
// npm run simulate
// Runs all fixtures through the pipeline offline (mock Claude, in-memory sinks),
// writes the resulting sheets/tasks/alerts to out/ and a Markdown report to
// tests/results/simulation-report.md. Exit code 1 if any fixture misbehaves.
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from '../src/config.js';
import { runSimulation } from '../src/simulation.js';
import { toCsv } from '../src/sim.js';
import { COLUMNS } from '../src/sheetColumns.js';

const sim = await runSimulation();
const outDir = path.join(ROOT, 'out');
mkdirSync(outDir, { recursive: true });

for (const [tab, rows] of Object.entries(sim.state.sheets)) {
  writeFileSync(path.join(outDir, `${tab}.csv`), toCsv(rows, COLUMNS[tab]));
}
writeFileSync(path.join(outDir, 'todoist-tasks.json'), JSON.stringify(sim.state.tasks, null, 2));
writeFileSync(path.join(outDir, 'alerts.txt'), sim.state.alerts.map((a) => `[${a.level}] ${a.title}\n${a.text}`).join('\n\n') + '\n');
writeFileSync(path.join(outDir, 'drafts.json'), JSON.stringify(sim.state.drafts, null, 2));
writeFileSync(path.join(outDir, 'renewal-digest.txt'), sim.renewalDigest + '\n');
writeFileSync(path.join(outDir, 'health-report.txt'), sim.healthReport + '\n');

const failed = sim.results.filter((r) => r.problems.length);
const lines = [];
lines.push('# Simulation report', '');
lines.push('Generated by `npm run simulate`. Offline run: Claude is **mocked** with the scripted answers in `tests/fixtures/emails.json`, and Google Sheets / Todoist / Slack are in-memory stand-ins. This proves the plumbing (checks, routing, retries, dead letters, replay, scheduled checks). It does not measure AI accuracy; see `npm run eval`.', '');
lines.push(`**Result: ${sim.results.length - failed.length}/${sim.results.length} fixtures behaved as expected.**`, '');
lines.push(`Mock Claude calls: ${sim.claudeCalls} · Simulated back-off waiting: ${Math.round(sim.simulatedWaitMs / 1000)} s`, '');
lines.push('| ID | Scenario | Outcome | Route / stage | Retries | Check |', '|---|---|---|---|---|---|');
for (const r of sim.results) {
  const where = r.result.route ?? r.result.stage ?? '';
  lines.push(`| ${r.id} | ${r.title} | ${r.result.outcome} | ${where} | ${r.result.retries ?? 0} | ${r.problems.length ? `❌ ${r.problems.join('; ')}` : '✅'} |`);
}
lines.push('', '## Totals', '');
for (const [tab, rows] of Object.entries(sim.state.sheets)) lines.push(`- ${tab}: ${rows.length} row(s)`);
lines.push(`- Todoist tasks: ${sim.state.tasks.length}`, `- Alerts: ${sim.state.alerts.length}`, `- Draft replies (not sent): ${sim.state.drafts.length}`);
lines.push('', '## S5 replay of the F30 dead letter (after "fixing" the Todoist project)', '');
if (sim.replay) {
  lines.push(`- Outcome: ${sim.replay.outcome}; dead letter ${sim.replay.deadLetterId} status: ${sim.replay.status}`);
  lines.push(`- Subscriptions rows for that email: before replay ${sim.replay.sheetRowsBefore}, after ${sim.replay.sheetRowsAfter} (no duplicate)`);
  lines.push(`- Todoist tasks for that email after replay: ${sim.replay.tasks}`);
}
lines.push('', '## S2 renewal digest', '', '```', sim.renewalDigest, '```');
lines.push('', '## S4 watchdog', '', `Fired: ${sim.watchdog.fired} (${sim.watchdog.reason})`);
lines.push('', '## S3 daily health report', '', '```', sim.healthReport, '```');
lines.push('', 'ALERT is the correct status here: the run deliberately includes two items that end in the dead-letter sheet (F25, F26).');
lines.push('', '## Example failure alert (F26)', '', '```', sim.results.find((r) => r.id === 'F26')?.result.alertText ?? '', '```', '');

mkdirSync(path.join(ROOT, 'tests', 'results'), { recursive: true });
writeFileSync(path.join(ROOT, 'tests', 'results', 'simulation-report.md'), lines.join('\n'));

console.log(lines.slice(0, 8 + sim.results.length).join('\n'));
console.log(`\nOutputs written to out/ and tests/results/simulation-report.md`);
if (failed.length) {
  console.error(`\n${failed.length} fixture(s) did not behave as expected.`);
  process.exit(1);
}
